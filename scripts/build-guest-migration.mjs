// Builds the single guest migration from the three tested drafts. Each draft's leading
// comment header (which says it is a draft) and its own begin;/commit; pair are removed,
// exactly one of each or the build fails; the bodies are otherwise byte-identical. The
// combined bodies run in ONE transaction, so a failed apply leaves nothing behind and can
// be retried. The provenance header pins the sha256 of each unmodified draft file.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),drafts=['trrc-guest-journal','trrc-guest-budget','trrc-guest-ops'].map(name=>`docs/sql/${name}-DRAFT-not-applied.sql`);
function body(path){
 const sql=readFileSync(resolve(root,path),'utf8').replace(/^(?:--[^\n]*\n)+/,'');
 if(!/^begin;\n/.test(sql))throw Error(`${path}: expected its body to open with one begin; line`);
 if(!/\ncommit;\n?$/.test(sql))throw Error(`${path}: expected its body to close with one commit; line`);
 return sql.replace(/^begin;\n/,'').replace(/\ncommit;\n?$/,'\n');
}
const parts=drafts.map(path=>({path,sha256:createHash('sha256').update(readFileSync(resolve(root,path))).digest('hex'),sql:body(path)}));
const header=`-- TRRC guest collection (design docs/superpowers/specs/2026-10-14-guest-collection-design.md).\n-- Generated by scripts/build-guest-migration.mjs from:\n${parts.map(p=>`--   ${p.path} sha256 ${p.sha256}`).join('\n')}\n-- Create the private bucket separately: insert into storage.buckets (id, name, public, file_size_limit) values ('trrc-guest-evidence', 'trrc-guest-evidence', false, 80106496);\n`;
mkdirSync(resolve(root,'supabase/migrations'),{recursive:true});
writeFileSync(resolve(root,'supabase/migrations/20261014000000_trrc_guest.sql'),header+'begin;\n'+parts.map(p=>`\n-- ===== ${p.path} =====\n`+p.sql).join('')+'\ncommit;\n');
console.log('Wrote supabase/migrations/20261014000000_trrc_guest.sql');
